export const statusRank: Record<Status, number> = { open: 0, soon: 1, upcoming: 2 };
export const statusLabel: Record<Status, string> = { open: '报名中', soon: '即将报名', upcoming: '下一届预告' };
export const feeLabel: Record<FeeType, string> = { free: '已核实免费', paid: '收费', unknown: '待核实' };
export const feeRank: Record<FeeType, number> = { free: 0, paid: 1, unknown: 2 };

export function startKey(item: Competition): string {
  const match = item.date.match(/(20\d{2})(?:-| 年 )(\d{1,2})/);
  return match ? `${match[1]}-${match[2].padStart(2, '0')}` : '9999-99';
}

export function deadlineKey(item: Competition): string {
  return item.deadline || startKey(item);
}

export function sortCompetitions(list: Competition[] = competitions): Competition[] {
  return [...list].sort((a, b) => {
    const byStatus = statusRank[a.status] - statusRank[b.status];
    if (byStatus !== 0) return byStatus;
    const byDate = deadlineKey(a).localeCompare(deadlineKey(b));
    if (byDate !== 0) return byDate;
    if (a.feeType !== b.feeType) return feeRank[a.feeType] - feeRank[b.feeType];
    return a.name.localeCompare(b.name, 'zh-CN');
  });
}

export function countByFee(list: Competition[] = competitions) {
  return {
    total: list.length,
    free: list.filter((c) => c.feeType === 'free').length,
    paid: list.filter((c) => c.feeType === 'paid').length,
    unknown: list.filter((c) => c.feeType === 'unknown').length,
  };
}
